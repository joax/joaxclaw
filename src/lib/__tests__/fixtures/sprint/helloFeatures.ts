/** 2026.9.4 with the given methods removed, e.g. a gateway where a plugin is not loaded. */
export function featuresWithout(methods: readonly string[], base: GatewayFeatures = FEATURES_2026_9_4): GatewayFeatures {
  const drop = new Set(methods)
  return { ...base, methods: (base.methods ?? []).filter((m) => !drop.has(m)) }
}

/** 2026.9.4 plus extra plugin/channel methods (e.g. joaxclaw-fs `memory.*`). */
export function featuresWith(methods: readonly string[], base: GatewayFeatures = FEATURES_2026_9_4): GatewayFeatures {
  return { ...base, methods: [...new Set([...(base.methods ?? []), ...methods])] }
}
